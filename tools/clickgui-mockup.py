"""Builds the ClickGUI mockup's data (design/clickgui/modules.js) from a dev-client module dump.

  python tools/testcfg.py setup
  sh tools/run-test.sh tools/examples/kmodules-dump.txt      # ShotBot's "kmodules": every module, setting and HUD widget
  python tools/testcfg.py restore
  python tools/clickgui-mockup.py [--horizon DIR] [--options FILE]

The dump holds the values of the config the dev client ran with (run/horizon, a copy of the owner's; to show the
owner's current setup, copy their horizon/modules, widgets, themes and shared.hzn into run/horizon between setup and
the run), the defaults, ranges, enum constants, groups, visibility tables and the HUD widgets. This adds the module and
HUD config names (from --horizon, default run/horizon) and the GUI scale (from --options, default run/options.txt), and
wraps it all as a script the page can load.
"""
import argparse
import json
import os
import re

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
DUMP = os.path.join(ROOT, 'tools', 'test-out', 'kmodules-dump', 'horizon-modules.json')
OUT = os.path.join(ROOT, 'design', 'clickgui', 'modules.js')

ap = argparse.ArgumentParser()
ap.add_argument('--horizon', default=os.path.join(ROOT, 'run', 'horizon'))
ap.add_argument('--options', default=os.path.join(ROOT, 'run', 'options.txt'))
args = ap.parse_args()

data = json.load(open(DUMP, encoding='utf-8'))
shared = json.load(open(os.path.join(args.horizon, 'shared.hzn'), encoding='utf-8'))
names = lambda sub: sorted(f[:-6] for f in os.listdir(os.path.join(args.horizon, sub)) if f.endswith('.hzn'))
data['configs'] = names('modules')
data['config'] = shared['modulesConfig']
data['hudConfigs'] = names('widgets')
data['hudConfig'] = shared['widgetsConfig']
scale = re.search(r'^guiScale:(\d+)', open(args.options, encoding='utf-8').read(), re.M)
data['guiScale'] = int(scale.group(1)) if scale and scale.group(1) != '0' else 2
os.makedirs(os.path.dirname(OUT), exist_ok=True)
with open(OUT, 'w', encoding='utf-8') as f:
    f.write('// Generated by tools/clickgui-mockup.py from a dev-client dump; do not edit.\n')
    f.write('window.HORIZON = ')
    json.dump(data, f, ensure_ascii=False, separators=(',', ':'))
    f.write(';\n')
print('%s: %d modules, %d settings, %d HUD widgets, GUI scale %d' % (
    OUT, len(data['modules']), sum(len(m['settings']) for m in data['modules']), len(data.get('hud', [])), data['guiScale']))
